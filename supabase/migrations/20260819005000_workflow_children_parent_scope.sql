-- TM-011: normalize workflow-child authorization to the parent opportunity.
--
-- This migration addresses three legacy policy families:
-- - opportunity_status_history: staff read must inherit parent pipeline scope;
-- - information_requests: staff read must inherit parent scope and platform_admin must
--   match the trusted-admin contract already enforced by server code;
-- - opportunity_activities: internal CRM activity must not leak to the seller, while
--   legitimate writable staff must be able to add activity on rows in their scope.

-- ---------------------------------------------------------------------------
-- Opportunity status history: generated by trusted triggers, read through parent.
-- ---------------------------------------------------------------------------
DROP POLICY IF EXISTS status_history_select_owner_or_admin ON public.opportunity_status_history;
DROP POLICY IF EXISTS opp_status_history_select_parent_scoped ON public.opportunity_status_history;

CREATE POLICY opp_status_history_select_parent_scoped
ON public.opportunity_status_history
FOR SELECT TO authenticated
USING (
  EXISTS (
    SELECT 1
    FROM public.vehicle_opportunities AS opp
    WHERE opp.id = opportunity_status_history.vehicle_opportunity_id
      AND (
        opp.partenaire_id = auth.uid()
        OR (
          opp.status <> 'brouillon'::public.opportunity_status
          AND private.can_read_pipeline_record(
            auth.uid(),
            opp.assigned_sales_agent_id,
            opp.assigned_group_id,
            COALESCE(opp.assigned_group, 'purchase'::public.staff_group)
          )
        )
      )
  )
);

